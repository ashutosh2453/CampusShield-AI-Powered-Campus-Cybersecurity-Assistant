import React, { useState } from 'react';
import { Copy, Check, Shield, AlertTriangle, ShieldCheck, HelpCircle, Info, MessageSquare } from 'lucide-react';
import { RiskGauge } from './RiskGauge';
import { RiskReasons } from './RiskReasons';
import { RecommendationCard } from './RecommendationCard';

export function AnalysisResult({ result, isFormDirty = false, onReanalyze, onAskAssistant }) {
  const [copied, setCopied] = useState(false);

  if (!result) return null;

  const {
    prediction = 'UNKNOWN',
    phishing_probability,
    risk_score = 0,
    risk_level = 'LOW',
    reasons = [],
    recommendation = '',
  } = result;

  const upperPrediction = String(prediction).toUpperCase();
  const upperLevel = String(risk_level).toUpperCase();
  const isPhishing = upperPrediction === 'PHISHING';
  const isLegitimate = upperPrediction === 'LEGITIMATE';
  const isLowRisk = upperLevel === 'LOW';

  // Format probability string safely
  let probStr = 'Unavailable';
  if (typeof phishing_probability === 'number' && !isNaN(phishing_probability)) {
    probStr = `${(phishing_probability * 100).toFixed(2)}%`;
  }

  // Generate text for copying
  const handleCopy = async () => {
    try {
      const reasonsText = Array.isArray(reasons) && reasons.length > 0
        ? reasons.map(r => `- ${r}`).join('\n')
        : '- No additional risk indicators detected';

      const summary = [
        'CampusShield Analysis',
        '----------------------------------------',
        `Prediction: ${upperPrediction}`,
        `Phishing Probability: ${probStr}`,
        `Risk Score: ${risk_score}/100`,
        `Risk Level: ${upperLevel}`,
        '',
        'Reasons:',
        reasonsText,
        '',
        'Recommendation:',
        recommendation || 'Verify through an official channel.',
        '----------------------------------------',
        'Generated by CampusShield AI Assistant',
      ].join('\n');

      if (navigator.clipboard && navigator.clipboard.writeText) {
        await navigator.clipboard.writeText(summary);
      } else {
        // Fallback for older or restricted environments
        const textArea = document.createElement('textarea');
        textArea.value = summary;
        document.body.appendChild(textArea);
        textArea.select();
        document.execCommand('copy');
        document.body.removeChild(textArea);
      }

      setCopied(true);
      setTimeout(() => setCopied(false), 2200);
    } catch (err) {
      console.error('Failed to copy analysis summary:', err);
    }
  };

  return (
    <div className="analysis-result-panel animate-fade-in" aria-live="polite">
      {/* Form modified notice */}
      {isFormDirty && (
        <div className="stale-result-banner">
          <Info className="w-4 h-4 mr-2 shrink-0 text-cyan-400" />
          <span>You have edited the message above. Click <strong>Analyze Message</strong> to update this analysis.</span>
          {onReanalyze && (
            <button onClick={onReanalyze} className="stale-reanalyze-link" type="button">
              Re-analyze now
            </button>
          )}
        </div>
      )}

      {/* Result Header */}
      <div className="result-header">
        <div className="result-header-left">
          <div className={`prediction-tag-pill ${isPhishing ? 'pred-phishing' : 'pred-legitimate'}`}>
            {isPhishing ? (
              <AlertTriangle className="w-5 h-5 mr-1.5 shrink-0" />
            ) : (
              <ShieldCheck className="w-5 h-5 mr-1.5 shrink-0" />
            )}
            <span className="font-extrabold tracking-wider">{upperPrediction}</span>
          </div>
          <span className="result-header-meta">
            Model classification outcome
          </span>
        </div>

        <div className="result-header-actions">
          {onAskAssistant && (
            <button
              onClick={() => onAskAssistant(result)}
              className="btn-ask-assistant"
              type="button"
              title="Ask CampusShield AI Assistant about this risk assessment"
            >
              <MessageSquare className="w-4 h-4 mr-1.5 text-cyan-300" />
              <span>Ask CampusShield about this result</span>
            </button>
          )}

          <button
            onClick={handleCopy}
            className="btn-copy-result"
            type="button"
            title="Copy formatted analysis to clipboard"
          >
            {copied ? (
              <>
                <Check className="w-4 h-4 text-emerald-400 mr-1.5" />
                <span>Copied!</span>
              </>
            ) : (
              <>
                <Copy className="w-4 h-4 mr-1.5" />
                <span>Copy Analysis</span>
              </>
            )}
          </button>
        </div>
      </div>

      {/* Main Results Grid */}
      <div className="result-grid">
        {/* Left Column: Visual Risk Gauge */}
        <div className="result-grid-gauge">
          <RiskGauge
            score={risk_score}
            level={upperLevel}
            probability={phishing_probability}
          />
        </div>

        {/* Right Column: Explainable Reasons & Details */}
        <div className="result-grid-details">
          <RiskReasons
            reasons={reasons}
            riskLevel={upperLevel}
          />

          <RecommendationCard
            recommendation={recommendation}
            riskLevel={upperLevel}
          />
        </div>
      </div>

      {/* Low-Risk Advisory Note (Never claim 100% safe) */}
      {isLegitimate && isLowRisk && (
        <div className="low-risk-advisory">
          <Shield className="w-5 h-5 text-emerald-400 shrink-0" />
          <p>
            <strong>Safety Note:</strong> No major risk indicators were detected. Continue to verify unexpected requests through trusted university or department channels.
          </p>
        </div>
      )}

      {/* Mandatory Safety Disclaimer */}
      <div className="safety-disclaimer-card">
        <HelpCircle className="w-4 h-4 text-slate-400 shrink-0 mt-0.5" />
        <p className="safety-disclaimer-text">
          CampusShield provides automated risk analysis and should not be treated as a guarantee that a message is safe or malicious. When in doubt, verify through an official channel.
        </p>
      </div>
    </div>
  );
}
